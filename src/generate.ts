/** Generate mock body for a type */
function generateMockBody(type: TypeIR, indent = '  '): string {
  switch (type.kind) {
    case 'object': {
      const obj = type as ObjectTypeIR;
      const props = obj.properties
        .map(p => {
          const mock = generateMockForType(p.type, indent + '  ', true);
          return `${indent}  ${p.name}: ${mock},`;
        })
        .join('\n');

      return `${indent}const defaults = {
${props}
${indent}};`;
    }

    case 'array': {
      const arr = type as ArrayTypeIR;
      const itemMock = generateMockForType(arr.items, indent + '  ', true);
      return `${indent}Array.from({ length: 3 }, () => ${itemMock})`;
    }

    case 'union': {
      const union = type as UnionTypeIR;
      const nonNull = union.types.filter(t => t.kind !== 'null' && t.kind !== 'undefined');
      if (nonNull.length === 0) return `${indent}null`;
      const picked = nonNull[Math.floor(Math.random() * nonNull.length)];
      if (!picked) return `${indent}null`;
      return generateMockBody(picked, indent);
    }

    default:
      return `${indent}${generateMockForType(type, indent, false)}`;
  }
}

/** Generate mock value for a type */
function generateMockForType(type: TypeIR, indent: string, inDefaults: boolean): string {
  switch (type.kind) {
    case 'object': {
      const obj = type as ObjectTypeIR;
      const props = obj.properties
        .map(p => {
          const mock = generateMockForType(p.type, indent + '  ', true);
          return `${indent}  ${p.name}: ${mock},`;
        })
        .join('\n');
      return `{${props}
${indent}}`;
    }

    case 'array': {
      const arr = type as ArrayTypeIR;
      const itemMock = generateMockForType(arr.items, indent + '  ', true);
      return `Array.from({ length: 3 }, () => ${itemMock})`;
    }

    case 'union': {
      const union = type as UnionTypeIR;
      const nonNull = union.types.filter(t => t.kind !== 'null' && t.kind !== 'undefined');
      if (nonNull.length === 0) return 'null';
      const picked = nonNull[Math.floor(Math.random() * nonNull.length)];
      if (!picked) return 'null';
      return generateMockForType(picked, indent, inDefaults);
    }

    case 'string': {
      const str = type as StringTypeIR;
      if (str.format === 'uuid') return 'faker.uuid()';
      if (str.format === 'email') return 'faker.email()';
      if (str.format === 'date-time') return 'faker.dateTime()';
      if (str.enum && str.enum.length > 0) return `faker.pick([${str.enum.map(v => JSON.stringify(v)).join(', ')}])`;
      return 'faker.string()';
    }

    case 'number':
      return 'faker.number()';

    case 'boolean':
      return 'faker.boolean()';

    case 'null':
      return 'null';

    case 'literal': {
      const lit = type as LiteralTypeIR;
      return JSON.stringify(lit.value);
    }

    case 'enum': {
      const en = type as EnumTypeIR;
      return `faker.pick([${en.values.map(v => JSON.stringify(v)).join(', ')}])`;
    }

    case 'reference': {
      const ref = type as ReferenceTypeIR;
      return `createMock${ref.name}()`;
    }

    default:
      return 'undefined';
  }
}


