/** Generate TanStack Query hooks */
function generateTanStackQueryHooks(ctx: GenContext, warnings: string[]): GeneratedFile[] {
  const { config, types, roots } = ctx;
  const lines: string[] = [];

  lines.push(`import { useQuery as useQueryFn, useMutation as useMutationFn, useQueryClient } from '@tanstack/react-query';`);
  lines.push(`import { ${roots.map(r => `fetch${r}`).join(', ')} } from './api.js';`);
  lines.push(`import type { ${roots.join(', ')} } from './types.js';`);
  lines.push(``);

  for (const rootName of roots) {
    const typeName = rootName;
    const fetchFn = `fetch${typeName}`;

    lines.push(`// ${typeName} hooks`);
    lines.push(`export function use${typeName}(params?: Record<string, string | number | boolean>) {`);
    lines.push(`  return useQueryFn({`);
    lines.push(`    queryKey: ['${toKebabCase(typeName)}', params],`);
    lines.push(`    queryFn: () => ${fetchFn}(params),`);
    lines.push(`  });`);
    lines.push(`}`);
    lines.push(``);

    lines.push(`export function use${typeName}Mutation() {`);
    lines.push(`  const queryClient = useQueryClient();`);
    lines.push(`  return useMutationFn({`);
    lines.push(`    mutationFn: (data: Partial<${typeName}>) => ${fetchFn}(undefined, {`);
    lines.push(`      method: 'POST',`);
    lines.push(`      headers: { 'Content-Type': 'application/json' },`);
    lines.push(`      body: JSON.stringify(data),`);
    lines.push(`    }),`);
    lines.push(`    onSuccess: () => {`);
    lines.push(`      queryClient.invalidateQueries({ queryKey: ['${toKebabCase(typeName)}'] });`);
    lines.push(`    },`);
    lines.push(`  });`);
    lines.push(`}`);
    lines.push(``);
  }

  return [{
    path: `${config.outDir}/hooks.ts`,
    content: lines.join('\n'),
    kind: 'hooks',
  }];
}

