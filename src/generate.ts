/**
 * Code Generation - transforms IR into TypeScript, Zod/Valibot, framework hooks, mocks
 */

import {
  TypeIR,
  NamedTypeIR,
  APISchemaIR,
  PropertyIR,
  ObjectTypeIR,
  UnionTypeIR,
  ArrayTypeIR,
  StringTypeIR,
  NumberTypeIR,
  BooleanTypeIR,
  NullTypeIR,
  UndefinedTypeIR,
  AnyTypeIR,
  LiteralTypeIR,
  EnumTypeIR,
  ReferenceTypeIR,
  RecursiveTypeIR,
  GenerationConfig,
  GenerationResult,
  GeneratedFile,
  DEFAULT_CONFIG,
} from './types.js';

/** Context for code generation */
interface GenContext {
  config: GenerationConfig;
  types: Map<string, NamedTypeIR>;
  roots: string[];
  discriminatedUnions: Map<string, { discriminator: string; members: string[] }>;
  recursiveTypes: Set<string>;
  generatedTypes: Set<string>;
  imports: Set<string>;
  warnings: string[];
}

/** Create generation context */
function createContext(ir: APISchemaIR, config: GenerationConfig): GenContext {
  return {
    config,
    types: ir.types,
    roots: ir.roots,
    discriminatedUnions: ir.discriminatedUnions,
    recursiveTypes: ir.recursiveTypes,
    generatedTypes: new Set(),
    imports: new Set(),
    warnings: [],
  };
}

/** Main entry: generate code from IR */
export function generateCode(ir: APISchemaIR, config: Partial<GenerationConfig> = {}): GenerationResult {
  const fullConfig: GenerationConfig = { ...DEFAULT_CONFIG, ...config };
  const files: GeneratedFile[] = [];
  const allWarnings: string[] = [];

  // Generate each output file with fresh context (but shared warnings)
  if (fullConfig.validator !== 'none') {
    const schemaCtx = createContext(ir, fullConfig);
    files.push(...generateSchemas(schemaCtx, allWarnings));
  }
  const typesCtx = createContext(ir, fullConfig);
  files.push(...generateTypes(typesCtx, allWarnings));
  const apiCtx = createContext(ir, fullConfig);
  files.push(...generateApi(apiCtx, allWarnings));
  if (fullConfig.generateHooks) {
    const hooksCtx = createContext(ir, fullConfig);
    files.push(...generateHooks(hooksCtx, allWarnings));
  }
  if (fullConfig.generateMocks) {
    const mocksCtx = createContext(ir, fullConfig);
    files.push(...generateMocks(mocksCtx, allWarnings));
  }
  const indexCtx = createContext(ir, fullConfig);
  files.push(generateIndex(indexCtx, allWarnings));

  // Collect all unique generated types for stats
  const allGeneratedTypes = new Set<string>();
  // We need to re-scan or track differently... for now just use roots + nested
  for (const [name] of ir.types) {
    allGeneratedTypes.add(name);
  }

  return {
    files,
    warnings: allWarnings,
    stats: {
      typesGenerated: allGeneratedTypes.size,
      filesWritten: files.length,
      discriminatedUnions: ir.discriminatedUnions.size,
      recursiveTypes: ir.recursiveTypes.size,
    },
  };
}

/** Generate Zod/Valibot schemas */
function generateSchemas(ctx: GenContext, warnings: string[]): GeneratedFile[] {
  const { config, types, generatedTypes } = ctx;
  const lines: string[] = [];

  // Header
  lines.push(`// Generated by api-typist - DO NOT EDIT`);
  lines.push(`// Schema validation with ${config.validator}`);
  lines.push('');

  // Imports
  if (config.validator === 'zod') {
    lines.push(`import { z } from 'zod';`);
  } else if (config.validator === 'valibot') {
    lines.push(`import * as v from 'valibot';`);
  }
  lines.push('');

  // First pass: collect all nested object types that need their own schema
  const nestedTypeNames = new Set<string>();
  
  function collectNested(type: TypeIR, baseName: string, prefix: string = ''): void {
    if (type.kind === 'object') {
      const obj = type as ObjectTypeIR;
      const fullName = baseName + (prefix ? '_' + prefix : '');
      if (fullName !== baseName) {
        nestedTypeNames.add(fullName);
      }
      for (const prop of obj.properties) {
        collectNested(prop.type, baseName, prefix ? `${prefix}.${prop.name}` : prop.name);
      }
    } else if (type.kind === 'array') {
      collectNested((type as ArrayTypeIR).items, baseName, prefix);
    } else if (type.kind === 'union') {
      for (const member of (type as UnionTypeIR).types) {
        collectNested(member, baseName, prefix);
      }
    }
  }

  // Collect all nested types from all root types
  for (const [name, namedType] of types) {
    collectNested(namedType.type, name);
  }

  // Second pass: generate all schemas, with nested types first
  const generatedNested = new Set<string>();

  // Helper to generate a schema and queue nested types first
  function generateAndQueue(type: TypeIR, name: string): string | null {
    // First generate nested types
    if (type.kind === 'object') {
      const obj = type as ObjectTypeIR;
      for (const prop of obj.properties) {
        if (prop.type.kind === 'object' || prop.type.kind === 'array') {
          const nestedName = `${name}_${prop.name}`;
          if (nestedTypeNames.has(nestedName) && !generatedNested.has(nestedName)) {
            generateAndQueue(prop.type, nestedName);
          }
        } else if (prop.type.kind === 'union') {
          for (const member of prop.type.types) {
            if (member.kind === 'object' || member.kind === 'array') {
              const nestedName = `${name}_${prop.name}`;
              if (nestedTypeNames.has(nestedName) && !generatedNested.has(nestedName)) {
                generateAndQueue(member, nestedName);
              }
            }
          }
        }
      }
    } else if (type.kind === 'array') {
      const arr = type as ArrayTypeIR;
      if (arr.items.kind === 'object' || arr.items.kind === 'union') {
        const nestedName = 'Item';
        if (nestedTypeNames.has(nestedName) && !generatedNested.has(nestedName)) {
          generateAndQueue(arr.items, nestedName);
        }
      }
    } else if (type.kind === 'union') {
      const union = type as UnionTypeIR;
      for (const member of union.types) {
        if (member.kind === 'object' || member.kind === 'array') {
          const nestedName = 'UnionMember';
          if (nestedTypeNames.has(nestedName) && !generatedNested.has(nestedName)) {
            generateAndQueue(member, nestedName);
          }
        }
      }
    }

    // Now generate this schema
    const schema = generateSchemaForOutput(type, name, ctx, generatedNested);
    if (schema && !generatedNested.has(name)) {
      generatedNested.add(name);
      lines.push(schema);
      lines.push('');
    }
    return schema;
  }

  // Generate for all root types
  for (const [name, namedType] of types) {
    if (generatedTypes.has(name)) continue;
    generatedTypes.add(name);
    generateAndQueue(namedType.type, name);
  }

  return [{
    path: `${config.outDir}/schemas.ts`,
    content: lines.join('\n'),
    kind: 'schemas',
  }];
}

/** Generate schema for output (used in queue) */
function generateSchemaForOutput(
  type: TypeIR, 
  name: string, 
  ctx: GenContext,
  generatedNested: Set<string>
): string | null {
  const { config, recursiveTypes } = ctx;
  const isRecursive = recursiveTypes.has(name);

  switch (type.kind) {
    case 'object': {
      const obj = type as ObjectTypeIR;
      
      if (config.validator === 'zod') {
        const shape = obj.properties
          .map(p => {
            const propSchema = getSchemaRef(p.type, `${name}_${p.name}`, ctx, generatedNested);
            if (!propSchema) return null;
            let field = `  ${p.name}: ${propSchema}`;
            if (p.optional) field += '.optional()';
            if (p.nullable && !p.optional) field += '.nullable()';
            return field + ',';
          })
          .filter(Boolean)
          .join('\n');

        let schema = `export const ${name}Schema = z.object({\n${shape}\n});`;
        if (isRecursive) {
          schema = `export const ${name}Schema: z.ZodType<${name}> = z.lazy(() => z.object({\n${shape}\n}));`;
        }
        return schema;
      } else if (config.validator === 'valibot') {
        const entries = obj.properties
          .map(p => {
            const propSchema = getSchemaRef(p.type, `${name}_${p.name}`, ctx, generatedNested);
            if (!propSchema) return null;
            let field = `  ${p.name}: ${propSchema}`;
            if (p.optional) field += `, v.optional()`;
            if (p.nullable && !p.optional) field += `, v.nullable()`;
            return field + ',';
          })
          .filter(Boolean)
          .join('\n');

        let schema = `export const ${name}Schema = v.object({\n${entries}\n});`;
        if (isRecursive) {
          schema = `export const ${name}Schema: v.BaseSchema<${name}> = v.lazy(() => v.object({\n${entries}\n}));`;
        }
        return schema;
      }
      return null;
    }

    case 'array': {
      const arr = type as ArrayTypeIR;
      const itemSchema = getSchemaRef(arr.items, 'Item', ctx, generatedNested);
      if (!itemSchema) return null;
      if (config.validator === 'zod') {
        return `z.array(${itemSchema})`;
      } else {
        return `v.array(${itemSchema})`;
      }
    }

    case 'union': {
      const union = type as UnionTypeIR;
      const schemas = union.types
        .map(t => getSchemaRef(t, 'UnionMember', ctx, generatedNested))
        .filter(Boolean);
      if (schemas.length === 0) return null;
      if (config.validator === 'zod') {
        return `z.union([${schemas.join(', ')}])`;
      } else {
        return `v.union([${schemas.join(', ')}])`;
      }
    }

    case 'string': {
      const str = type as StringTypeIR;
      if (config.validator === 'zod') {
        let schema = 'z.string()';
        if (str.format === 'uuid') schema += '.uuid()';
        else if (str.format === 'email') schema += '.email()';
        else if (str.format === 'date-time') schema += '.datetime()';
        else if (str.format === 'date') schema += '.date()';
        else if (str.format === 'url') schema += '.url()';
        if (str.pattern) schema += `.regex(${JSON.stringify(str.pattern)})`;
        if (str.minLength) schema += `.min(${str.minLength})`;
        if (str.maxLength) schema += `.max(${str.maxLength})`;
        if (str.enum && str.enum.length > 0) {
          const vals = str.enum.map(v => JSON.stringify(v)).join(', ');
          schema = `z.enum([${vals}])`;
        }
        return schema;
      } else {
        let schema = 'v.string()';
        if (str.format === 'uuid') schema += ', v.uuid()';
        else if (str.format === 'email') schema += ', v.email()';
        else if (str.format === 'date-time') schema += ', v.isoTimestamp()';
        else if (str.format === 'date') schema += ', v.isoDate()';
        else if (str.format === 'url') schema += ', v.url()';
        if (str.pattern) schema += `, v.regex(${JSON.stringify(str.pattern)})`;
        if (str.minLength) schema += `, v.minLength(${str.minLength})`;
        if (str.maxLength) schema += `, v.maxLength(${str.maxLength})`;
        if (str.enum && str.enum.length > 0) {
          const vals = str.enum.map(v => JSON.stringify(v)).join(', ');
          schema = `v.picklist([${vals}])`;
        }
        return schema;
      }
    }

    case 'number': {
      const num = type as NumberTypeIR;
      if (config.validator === 'zod') {
        let schema = num.format === 'int32' || num.format === 'int64' ? 'z.number().int()' : 'z.number()';
        if (num.minimum !== undefined) schema += `.min(${num.minimum}${num.exclusiveMinimum ? ', { exclusive: true }' : ''})`;
        if (num.maximum !== undefined) schema += `.max(${num.maximum}${num.exclusiveMaximum ? ', { exclusive: true }' : ''})`;
        if (num.multipleOf !== undefined) schema += `.multipleOf(${num.multipleOf})`;
        return schema;
      } else {
        let schema = 'v.number()';
        if (num.format === 'int32' || num.format === 'int64') schema += ', v.integer()';
        if (num.minimum !== undefined) schema += `, v.minValue(${num.minimum})`;
        if (num.maximum !== undefined) schema += `, v.maxValue(${num.maximum})`;
        if (num.multipleOf !== undefined) schema += `, v.multipleOf(${num.multipleOf})`;
        return schema;
      }
    }

    case 'boolean':
      return config.validator === 'zod' ? 'z.boolean()' : 'v.boolean()';

    case 'null':
      return config.validator === 'zod' ? 'z.null()' : 'v.null_()';

    case 'undefined':
      return config.validator === 'zod' ? 'z.undefined()' : 'v.undefined_()';

    case 'any':
      return config.validator === 'zod' ? 'z.any()' : 'v.any()';

    case 'literal': {
      const lit = type as LiteralTypeIR;
      const val = JSON.stringify(lit.value);
      return config.validator === 'zod' ? `z.literal(${val})` : `v.literal(${val})`;
    }

    case 'enum': {
      const en = type as EnumTypeIR;
      const vals = en.values.map(v => JSON.stringify(v)).join(', ');
      return config.validator === 'zod' ? `z.enum([${vals}])` : `v.picklist([${vals}])`;
    }

    case 'reference': {
      const ref = type as ReferenceTypeIR;
      return `${ref.name}Schema`;
    }

    case 'recursive': {
      const rec = type as RecursiveTypeIR;
      return `${rec.name}Schema`;
    }

    default:
      ctx.warnings.push(`Unknown type kind: ${(type as TypeIR).kind}`);
      return null;
  }
}

/** Get schema reference for nested types */
function getSchemaRef(
  type: TypeIR,
  name: string,
  ctx: GenContext,
  generatedNested: Set<string>
): string | null {
  const { config } = ctx;

  switch (type.kind) {
    case 'object': {
      if (generatedNested.has(name)) {
        return `${name}Schema`;
      }
      // Inline object
      return generateSchemaForOutput(type, name, ctx, generatedNested);
    }

    case 'array': {
      const arr = type as ArrayTypeIR;
      const itemName = name === 'Item' ? 'Item' : name;
      if (arr.items.kind === 'object' || arr.items.kind === 'union') {
        const itemRef = getSchemaRef(arr.items, itemName, ctx, generatedNested);
        if (!itemRef) return null;
        if (config.validator === 'zod') return `z.array(${itemRef})`;
        return `v.array(${itemRef})`;
      }
      return generateSchemaForOutput(type, name, ctx, generatedNested);
    }

    case 'union': {
      if (generatedNested.has(name)) {
        return `${name}Schema`;
      }
      return generateSchemaForOutput(type, name, ctx, generatedNested);
    }

    // Primitive types - inline
    case 'string': {
      const str = type as StringTypeIR;
      if (config.validator === 'zod') {
        let schema = 'z.string()';
        if (str.format === 'uuid') schema += '.uuid()';
        else if (str.format === 'email') schema += '.email()';
        else if (str.format === 'date-time') schema += '.datetime()';
        else if (str.format === 'date') schema += '.date()';
        else if (str.format === 'url') schema += '.url()';
        if (str.pattern) schema += `.regex(${JSON.stringify(str.pattern)})`;
        if (str.minLength) schema += `.min(${str.minLength})`;
        if (str.maxLength) schema += `.max(${str.maxLength})`;
        if (str.enum && str.enum.length > 0) {
          const vals = str.enum.map(v => JSON.stringify(v)).join(', ');
          schema = `z.enum([${vals}])`;
        }
        return schema;
      } else {
        let schema = 'v.string()';
        if (str.format === 'uuid') schema += ', v.uuid()';
        else if (str.format === 'email') schema += ', v.email()';
        else if (str.format === 'date-time') schema += ', v.isoTimestamp()';
        else if (str.format === 'date') schema += ', v.isoDate()';
        else if (str.format === 'url') schema += ', v.url()';
        if (str.pattern) schema += `, v.regex(${JSON.stringify(str.pattern)})`;
        if (str.minLength) schema += `, v.minLength(${str.minLength})`;
        if (str.maxLength) schema += `, v.maxLength(${str.maxLength})`;
        if (str.enum && str.enum.length > 0) {
          const vals = str.enum.map(v => JSON.stringify(v)).join(', ');
          schema = `v.picklist([${vals}])`;
        }
        return schema;
      }
    }

    case 'number': {
      const num = type as NumberTypeIR;
      if (config.validator === 'zod') {
        let schema = num.format === 'int32' || num.format === 'int64' ? 'z.number().int()' : 'z.number()';
        if (num.minimum !== undefined) schema += `.min(${num.minimum}${num.exclusiveMinimum ? ', { exclusive: true }' : ''})`;
        if (num.maximum !== undefined) schema += `.max(${num.maximum}${num.exclusiveMaximum ? ', { exclusive: true }' : ''})`;
        if (num.multipleOf !== undefined) schema += `.multipleOf(${num.multipleOf})`;
        return schema;
      } else {
        let schema = 'v.number()';
        if (num.format === 'int32' || num.format === 'int64') schema += ', v.integer()';
        if (num.minimum !== undefined) schema += `, v.minValue(${num.minimum})`;
        if (num.maximum !== undefined) schema += `, v.maxValue(${num.maximum})`;
        if (num.multipleOf !== undefined) schema += `, v.multipleOf(${num.multipleOf})`;
        return schema;
      }
    }

    case 'boolean':
      return config.validator === 'zod' ? 'z.boolean()' : 'v.boolean()';

    case 'null':
      return config.validator === 'zod' ? 'z.null()' : 'v.null_()';

    case 'undefined':
      return config.validator === 'zod' ? 'z.undefined()' : 'v.undefined_()';

    case 'any':
      return config.validator === 'zod' ? 'z.any()' : 'v.any()';

    case 'literal': {
      const lit = type as LiteralTypeIR;
      const val = JSON.stringify(lit.value);
      return config.validator === 'zod' ? `z.literal(${val})` : `v.literal(${val})`;
    }

    case 'enum': {
      const en = type as EnumTypeIR;
      const vals = en.values.map(v => JSON.stringify(v)).join(', ');
      return config.validator === 'zod' ? `z.enum([${vals}])` : `v.picklist([${vals}])`;
    }

    case 'reference': {
      const ref = type as ReferenceTypeIR;
      return `${ref.name}Schema`;
    }

    case 'recursive': {
      const rec = type as RecursiveTypeIR;
      return `${rec.name}Schema`;
    }

    default:
      return null;
  }
}

/** Generate TypeScript interfaces/type aliases */
function generateTypes(ctx: GenContext, warnings: string[]): GeneratedFile[] {
  const { config, types, generatedTypes } = ctx;
  const lines: string[] = [];

  lines.push(`// Generated by api-typist - DO NOT EDIT`);
  lines.push(`// TypeScript types`);
  lines.push('');

  if (config.validator !== 'none') {
    lines.push(`import type { z } from '${config.validator === 'zod' ? 'zod' : 'valibot'}';`);
    lines.push('');
  }

  // First pass: collect all nested object types that need their own interface
  const nestedTypeNames = new Set<string>();
  
  function collectNested(type: TypeIR, baseName: string, prefix: string = ''): void {
    if (type.kind === 'object') {
      const obj = type as ObjectTypeIR;
      const fullName = baseName + (prefix ? '_' + prefix : '');
      if (fullName !== baseName) {
        nestedTypeNames.add(fullName);
      }
      for (const prop of obj.properties) {
        collectNested(prop.type, baseName, prefix ? `${prefix}.${prop.name}` : prop.name);
      }
    } else if (type.kind === 'array') {
      collectNested((type as ArrayTypeIR).items, baseName, prefix);
    } else if (type.kind === 'union') {
      for (const member of (type as UnionTypeIR).types) {
        collectNested(member, baseName, prefix);
      }
    }
  }

  // Collect all nested types from all root types
  for (const [name, namedType] of types) {
    collectNested(namedType.type, name);
  }

  // Second pass: generate all types, with nested types first
  const generatedNested = new Set<string>();

  // Helper to generate a type and queue nested types first
  function generateAndQueue(type: TypeIR, name: string): string | null {
    // First generate nested types
    if (type.kind === 'object') {
      const obj = type as ObjectTypeIR;
      for (const prop of obj.properties) {
        if (prop.type.kind === 'object' || prop.type.kind === 'array') {
          const nestedName = `${name}_${prop.name}`;
          if (nestedTypeNames.has(nestedName) && !generatedNested.has(nestedName)) {
            generateAndQueue(prop.type, nestedName);
          }
        } else if (prop.type.kind === 'union') {
          for (const member of prop.type.types) {
            if (member.kind === 'object' || member.kind === 'array') {
              const nestedName = `${name}_${prop.name}`;
              if (nestedTypeNames.has(nestedName) && !generatedNested.has(nestedName)) {
                generateAndQueue(member, nestedName);
              }
            }
          }
        }
      }
    } else if (type.kind === 'array') {
      const arr = type as ArrayTypeIR;
      if (arr.items.kind === 'object' || arr.items.kind === 'union') {
        const nestedName = 'Item';
        if (nestedTypeNames.has(nestedName) && !generatedNested.has(nestedName)) {
          generateAndQueue(arr.items, nestedName);
        }
      }
    } else if (type.kind === 'union') {
      const union = type as UnionTypeIR;
      for (const member of union.types) {
        if (member.kind === 'object' || member.kind === 'array') {
          const nestedName = 'UnionMember';
          if (nestedTypeNames.has(nestedName) && !generatedNested.has(nestedName)) {
            generateAndQueue(member, nestedName);
          }
        }
      }
    }

    // Now generate this type
    const tsType = generateTsTypeForOutput(type, name, ctx, generatedNested);
    if (tsType && !generatedNested.has(name)) {
      generatedNested.add(name);
      lines.push(tsType);
      lines.push('');
    }
    return tsType;
  }

  // Generate for all root types
  for (const [name, namedType] of types) {
    if (generatedTypes.has(name)) continue;
    generatedTypes.add(name);
    generateAndQueue(namedType.type, name);
  }

  return [{
    path: `${config.outDir}/types.ts`,
    content: lines.join('\n'),
    kind: 'types',
  }];
}

/** Generate TypeScript type for output (used in queue) */
function generateTsTypeForOutput(
  type: TypeIR, 
  name: string, 
  ctx: GenContext,
  generatedNested: Set<string>
): string | null {
  const { config, recursiveTypes } = ctx;
  const isRecursive = recursiveTypes.has(name);
  const useInterface = config.useInterfaces && type.kind === 'object';

  switch (type.kind) {
    case 'object': {
      const obj = type as ObjectTypeIR;
      const props = obj.properties
        .map(p => {
          const propType = generateTsTypeRef(p.type, `${name}_${p.name}`, ctx, generatedNested);
          if (!propType) return null;
          const opt = p.optional ? '?' : '';
          const desc = p.description ? ` /** ${p.description} */` : '';
          return `  ${p.name}${opt}: ${propType};${desc}`;
        })
        .filter(Boolean)
        .join('\n');

      if (useInterface) {
        return `export interface ${name} {\n${props}\n}`;
      } else {
        return `export type ${name} = {\n${props}\n};`;
      }
    }

    case 'array': {
      const arr = type as ArrayTypeIR;
      const itemType = generateTsTypeRef(arr.items, 'Item', ctx, generatedNested);
      if (!itemType) return null;
      return `${itemType}[]`;
    }

    case 'union': {
      const union = type as UnionTypeIR;
      const typesStr = union.types
        .map(t => generateTsTypeRef(t, 'UnionMember', ctx, generatedNested))
        .filter(Boolean)
        .join(' | ');
      return typesStr;
    }

    case 'string': {
      const str = type as StringTypeIR;
      if (str.enum && str.enum.length > 0) {
        return str.enum.map(v => JSON.stringify(v)).join(' | ');
      }
      return 'string';
    }

    case 'number':
      return 'number';

    case 'boolean':
      return 'boolean';

    case 'null':
      return 'null';

    case 'undefined':
      return 'undefined';

    case 'any':
      return 'any';

    case 'literal': {
      const lit = type as LiteralTypeIR;
      return JSON.stringify(lit.value);
    }

    case 'enum': {
      const en = type as EnumTypeIR;
      return en.values.map(v => JSON.stringify(v)).join(' | ');
    }

    case 'reference': {
      const ref = type as ReferenceTypeIR;
      return ref.name;
    }

    case 'recursive': {
      const rec = type as RecursiveTypeIR;
      return rec.name;
    }

    default:
      ctx.warnings.push(`Unknown type kind for TS: ${(type as TypeIR).kind}`);
      return null;
  }
}

/** Generate a TypeScript type reference for nested types */
function generateTsTypeRef(
  type: TypeIR, 
  name: string, 
  ctx: GenContext,
  generatedNested: Set<string>
): string | null {
  const { config, recursiveTypes } = ctx;

  switch (type.kind) {
    case 'object': {
      // If this is a nested type that should be generated separately
      if (generatedNested.has(name)) {
        return name;
      }
      // For inline objects (not in nested set), generate inline
      const obj = type as ObjectTypeIR;
      const props = obj.properties
        .map(p => {
          const propType = generateTsTypeRef(p.type, `${name}_${p.name}`, ctx, generatedNested);
          if (!propType) return null;
          const opt = p.optional ? '?' : '';
          return `  ${p.name}${opt}: ${propType};`;
        })
        .filter(Boolean)
        .join('\n');
      return `{\n${props}\n}`;
    }

    case 'array': {
      const arr = type as ArrayTypeIR;
      const itemType = generateTsTypeRef(arr.items, 'Item', ctx, generatedNested);
      if (!itemType) return null;
      return `${itemType}[]`;
    }

    case 'union': {
      const union = type as UnionTypeIR;
      const typesStr = union.types
        .map(t => generateTsTypeRef(t, 'UnionMember', ctx, generatedNested))
        .filter(Boolean)
        .join(' | ');
      return typesStr;
    }

    case 'string': {
      const str = type as StringTypeIR;
      if (str.enum && str.enum.length > 0) {
        return str.enum.map(v => JSON.stringify(v)).join(' | ');
      }
      return 'string';
    }

    case 'number':
      return 'number';

    case 'boolean':
      return 'boolean';

    case 'null':
      return 'null';

    case 'undefined':
      return 'undefined';

    case 'any':
      return 'any';

    case 'literal': {
      const lit = type as LiteralTypeIR;
      return JSON.stringify(lit.value);
    }

    case 'enum': {
      const en = type as EnumTypeIR;
      return en.values.map(v => JSON.stringify(v)).join(' | ');
    }

    case 'reference': {
      const ref = type as ReferenceTypeIR;
      return ref.name;
    }

    case 'recursive': {
      const rec = type as RecursiveTypeIR;
      return rec.name;
    }

    default:
      return null;
  }
}

/** Generate fetch API wrappers */
function generateApi(ctx: GenContext, warnings: string[]): GeneratedFile[] {
  const { config, types, roots } = ctx;
  const lines: string[] = [];

  lines.push(`// Generated by api-typist - DO NOT EDIT`);
  lines.push(`// Typed API fetch wrappers`);
  lines.push('');

  // Imports
  lines.push(`import type { ${roots.join(', ')} } from './types.js';`);
  if (config.validator !== 'none') {
    lines.push(`import { ${roots.map(r => `${r}Schema`).join(', ')} } from './schemas.js';`);
  }
  lines.push('');

  // Base URL and fetch function
  const baseUrl = config.baseUrl || '';
  const fetchFn = config.fetchFunctionName || 'fetch';
  const defaultHeaders = config.headers ? JSON.stringify(config.headers, null, 2) : '{}';

  lines.push(`const BASE_URL = ${JSON.stringify(baseUrl)};`);
  lines.push(`const DEFAULT_HEADERS = ${defaultHeaders} as const;`);
  lines.push('');

  // Generate fetch wrapper for each root type
  for (const rootName of roots) {
    const namedType = types.get(rootName);
    if (!namedType) continue;

    const typeName = rootName;
    const schemaName = `${rootName}Schema`;

    // Determine endpoint from type name (convention: TypeName -> /type-name)
    const endpoint = toKebabCase(rootName.replace(/^(Response|Data|Result)$/, ''));

    lines.push(`// ${typeName} API`);
    lines.push(`export async function fetch${typeName}(`);
    lines.push(`  params?: Record<string, string | number | boolean>,`);
    lines.push(`  options?: RequestInit`);
    lines.push(`): Promise<${typeName}> {`);
    lines.push(`  const url = new URL(BASE_URL + '/${endpoint}');`);
    lines.push(`  if (params) {`);
    lines.push(`    Object.entries(params).forEach(([key, value]) => {`);
    lines.push(`      url.searchParams.append(key, String(value));`);
    lines.push(`    });`);
    lines.push(`  }`);
    lines.push(`  const response = await ${fetchFn}(url.toString(), {`);
    lines.push(`    headers: { ...DEFAULT_HEADERS, ...options?.headers },`);
    lines.push(`    ...options,`);
    lines.push(`  });`);
    lines.push(`  if (!response.ok) {`);
    lines.push(`    throw new Error(\`HTTP \${response.status}: \${response.statusText}\`);`);
    lines.push(`  }`);
    lines.push(`  const data = await response.json();`);
    if (config.addRuntimeValidation && config.validator !== 'none') {
      lines.push(`  return ${schemaName}.parse(data);`);
    } else {
      lines.push(`  return data as ${typeName};`);
    }
    lines.push(`}`);
    lines.push('');
  }

  return [{
    path: `${config.outDir}/api.ts`,
    content: lines.join('\n'),
    kind: 'api',
  }];
}

